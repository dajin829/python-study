# 第 6 天：秒数转换器（小挑战）
# 输入一个秒数 → 输出 X小时Y分Z秒
# 例：3661 → 1小时1分钟1秒

time = input("多少秒？")
time = int(time)          # input 进来是字符串，转数字才能算

# 我的解法：用第 4 天学的 int() 截断小数，再用减法扣掉已经算过的部分
a = time / 3600
a = int(a)                # 小时：3661/3600=1.0169 → 截断成 1

b = (time - 3600 * a) / 60
b = int(b)                # 分钟：扣掉小时后，61/60=1.0166 → 截断成 1

c = time - a * 3600 - b * 60   # 秒：把小时和分钟都扣掉，剩下的就是秒

print(f"{a}小时{b}分钟{c}秒")
