# 第 5 天：字符串操作
# 四个常用工具：len() 长度 / .upper() 转大写 / .strip() 去首尾空格 / 切片 s[a:b]

s = " Hello Python"

print(len(s))        # 长度：空格也算一个字符。1+5+1+6 = 13
print(s.upper())     # 全大写：只转英文字母，中文不变
print(s.strip())     # 去掉首尾空格：句子中间的空格不动
print(s[0:5])        # 切片：切出 b-a 个字符，含头不含尾（跟 range 一个规律）

